vm.runInNewContext(s,sandbox);
const api=sandbox.window.OMODOS_TECH_PERFORMANCE_TEST;
assert(api,'test API should be exposed');
assert(Math.abs(api.calcOeeRow({Availability:'50%',Performance:'80%',Quality:'90%'}).oee-0.36)<1e-10,'percent strings should normalize correctly');
