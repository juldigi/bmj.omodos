const fs=require('fs'),vm=require('vm'),assert=require('assert');
const s=fs.readFileSync('public/omodos4/technical-performance.js','utf8');
assert(s.includes('OEE = Availability × Performance × Quality'));
assert(s.includes('OEE × Utilization'));
assert(s.includes('technicalPerformanceRead'));
assert(s.includes('technicalPerformanceImport'));
assert(s.includes('requireSuperadmin')===false,'Superadmin enforcement belongs in Worker, not frontend');
assert(s.includes('if(!isSuperadmin())'),'Frontend must hide module from non-Superadmin');
assert(s.includes("MTC Downtime"),'Maintenance data must use MTC-specific source columns');
assert(s.includes('sheet_to_json'),'Excel workbook parser should be available');
